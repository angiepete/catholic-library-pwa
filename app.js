let currentCategory = "all";
let bookmarks = JSON.parse(localStorage.getItem("catholicBookmarks") || "[]");

function renderList(filter = "") {
  const container = document.getElementById("content");
  let items = [];
  if (currentCategory === "all") {
    Object.values(library).forEach(cat => items.push(...cat));
  } else {
    items = library[currentCategory] || [];
  }
  if (filter) {
    const q = filter.toLowerCase();
    items = items.filter(i => i.title.toLowerCase().includes(q) || i.content.toLowerCase().includes(q));
  }
  if (items.length === 0) {
    container.innerHTML = "<p style='color:#a0a0b0'>No results.</p>";
    return;
  }
  container.innerHTML = `<div class="book-list">${items.map(item => `\n    <div class="book-item" onclick="openReader('${item.id}')">\n      <h3>${item.title}</h3>\n      <p>${item.category}</p>\n    </div>`).join("")}</div>`;
}

function openReader(id) {
  let item = null;
  for (const cat of Object.values(library)) {
    item = cat.find(i => i.id === id);
    if (item) break;
  }
  if (!item) return;
  const isBookmarked = bookmarks.includes(id);
  document.getElementById("content").innerHTML = `\n    <div class="reader">\n      <h2>${item.title}</h2>\n      <div class="content">${item.content}</div>\n      <button class="bookmark-btn" onclick="toggleBookmark('${id}')">\n        ${isBookmarked ? "★ Remove Bookmark" : "☆ Add Bookmark"}\n      </button>\n    </div>`;
}

function toggleBookmark(id) {
  if (bookmarks.includes(id)) {
    bookmarks = bookmarks.filter(b => b !== id);
  } else {
    bookmarks.push(id);
  }
  localStorage.setItem("catholicBookmarks", JSON.stringify(bookmarks));
  openReader(id);
}

function setCategory(cat) {
  currentCategory = cat;
  document.querySelectorAll(".tab").forEach(t => t.classList.remove("active"));
  document.querySelector(`[data-cat="${cat}"]`).classList.add("active");
  renderList(document.getElementById("search").value);
}

document.addEventListener("DOMContentLoaded", () => {
  renderList();
  document.getElementById("search").addEventListener("input", e => renderList(e.target.value));
});

